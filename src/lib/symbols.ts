// Special characters (plan 09 task 9.6, issue #89): the bundled table behind
// the Insert > Special Characters popover. ~300 of the characters people
// actually insert, each with a searchable name — typing "copyright" finds ©,
// "arrow right" finds →. The popover renders the character glyphs directly,
// and the insert is the raw character as plain text (no markup, golden rule 1).
//
// Codepage safety (plan 09 AC5): the character is inserted into the document
// as a single UTF-8 code point. The save pipeline writes UTF-8 (the fs
// safety core is untouched), so a file that receives © stays valid UTF-8 on
// Windows and everywhere else — nothing here ever transcodes.
//
// "Recent" (plan 09 §2.5): the last-inserted characters, in insertion order
// (most recent first), persisted in localStorage like the find-panel position
// — a view convenience, never part of the document. The popover's first row.

export type SymbolCategory =
  | "currency"
  | "math"
  | "arrows"
  | "bullets"
  | "typography"
  | "symbols";

export interface SymbolCategorySpec {
  id: SymbolCategory;
  label: string;
}

// The six plan 09 §2.5 categories, in popover order.
export const SYMBOL_CATEGORIES: readonly SymbolCategorySpec[] = [
  { id: "currency", label: "Currency" },
  { id: "math", label: "Math" },
  { id: "arrows", label: "Arrows" },
  { id: "bullets", label: "Bullets" },
  { id: "typography", label: "Typography" },
  { id: "symbols", label: "Symbols" },
];

export function symbolCategoryById(id: string): SymbolCategorySpec | null {
  return SYMBOL_CATEGORIES.find((c) => c.id === id) ?? null;
}

