// All entries whose name contains `query` (case-insensitive), in table order.
// An empty query returns the whole table.
export function searchSymbols(query: string): SymbolEntry[] {
  const q = query.trim().toLowerCase();
  if (!q) return [...SYMBOLS];
  return SYMBOLS.filter((s) => s.name.toLowerCase().includes(q));
}

// The entries of one category, in table order.
export function symbolsInCategory(category: SymbolCategory): SymbolEntry[] {
  return SYMBOLS.filter((s) => s.category === category);
}

// The whole table, one entry per character (the popover dedupes by character
// when merging recents with the filtered table).
export const SYMBOL_COUNT = SYMBOLS.length;

// ---------------------------------------------------------------------------
// Recent characters
// ---------------------------------------------------------------------------

const RECENT_STORAGE_KEY = "quillmd.symbols.recent";
const RECENT_MAX = 24;

function readRecentRaw(): string[] {
  try {
    const raw = globalThis.localStorage?.getItem(RECENT_STORAGE_KEY);
    if (!raw) return [];
    const parsed: unknown = JSON.parse(raw);
    if (!Array.isArray(parsed)) return [];
    return parsed.filter(
      (c): c is string =>
        typeof c === "string" && c.length > 0 && [...c].length === 1,
    );
  } catch {
    return [];
  }
}

// The recent characters, most recent first (max RECENT_MAX, deduplicated).
export function getRecentSymbols(): string[] {
  return readRecentRaw().slice(0, RECENT_MAX);
}

// Records an insert: moves `char` to the front, deduplicates, truncates.
// No-op if the character is empty.
export function recordSymbolInsert(char: string): string[] {
  if (!char || [...char].length !== 1) return getRecentSymbols();
  const next = [char, ...getRecentSymbols().filter((c) => c !== char)].slice(
    0,
    RECENT_MAX,
  );
  try {
    globalThis.localStorage?.setItem(RECENT_STORAGE_KEY, JSON.stringify(next));
  } catch {
    // localStorage unavailable (private mode, quota) — recent is a
    // convenience, not correctness.
  }
  return next;
}
